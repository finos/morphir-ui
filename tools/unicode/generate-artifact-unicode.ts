import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { parseArgs } from 'node:util'
import { fileURLToPath } from 'node:url'
import { gzipSync, gunzipSync } from 'node:zlib'
import { format, resolveConfig } from 'prettier'
import manifest from './manifest.json'

// bun tools/unicode/generate-artifact-unicode.ts --check: offline source/table verification.
// Without flags, regenerate from bundled verified sources. --refresh fetches the exact
// official source bytes named in manifest.json and refuses any checksum difference.

const { values } = parseArgs({
  options: { check: { type: 'boolean' }, refresh: { type: 'boolean' } },
})
if (values.check && values.refresh) throw new Error('--check and --refresh are mutually exclusive')
const digest = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex')
const sources = new Map<string, string>()
for (const source of [...manifest.sources, manifest.license]) {
  const license = source.file === 'LICENSE.txt'
  const file = new URL(license ? './LICENSE.txt' : `./sources/${source.file}.gz`, import.meta.url)
  let bytes: Uint8Array
  if (values.refresh) {
    const response = await fetch(source.url)
    if (!response.ok) throw new Error(`Unable to fetch ${source.url}: ${response.status}`)
    bytes = new Uint8Array(await response.arrayBuffer())
  } else {
    const saved = await readFile(file)
    bytes = license ? saved : gunzipSync(saved)
  }
  if (digest(bytes) !== source.sha256)
    throw new Error(`Unicode source checksum mismatch: ${source.file}`)
  sources.set(source.file, new TextDecoder('utf-8', { fatal: true }).decode(bytes))
  if (values.refresh) {
    await mkdir(new URL('./sources/', import.meta.url), { recursive: true })
    await writeFile(file, license ? bytes : gzipSync(bytes, { level: 9 }))
  }
}

const exclusions = new Set<number>()
for (const line of sources.get('DerivedNormalizationProps-17.txt')!.split('\n')) {
  const [range, property] = line
    .split('#')[0]!
    .split(';')
    .map((field) => field.trim())
  if (property !== 'Full_Composition_Exclusion') continue
  const [start, end = start] = range!.split('..').map((point) => Number.parseInt(point, 16))
  for (let point = start!; point <= end!; point++) exclusions.add(point)
}
const decomposition: Record<number, { compatibility: boolean; mapping: number[] }> = {}
const combining: Record<number, number> = {}
const composition: Record<number, Record<number, number>> = {}
for (const line of sources.get('UnicodeData-17.txt')!.split('\n')) {
  if (!line) continue
  const fields = line.split(';')
  const point = Number.parseInt(fields[0]!, 16)
  const combiningClass = Number(fields[3])
  if (combiningClass !== 0) combining[point] = combiningClass
  const rawMapping = fields[5]!
  if (!rawMapping) continue
  const compatibility = rawMapping.startsWith('<')
  const mapping = rawMapping
    .replace(/^<[^>]+> /, '')
    .split(' ')
    .map((part) => Number.parseInt(part, 16))
  decomposition[point] = { compatibility, mapping }
  if (!compatibility && mapping.length === 2 && !exclusions.has(point)) {
    const [first, second] = mapping as [number, number]
    composition[first] ??= {}
    if (composition[first]![second] !== undefined)
      throw new Error('Duplicate canonical composition')
    composition[first]![second] = point
  }
}
const folding: Record<number, number[]> = {}
for (const line of sources.get('CaseFolding-9.txt')!.split('\n')) {
  const [point, status, mapping] = line
    .split('#')[0]!
    .split(';')
    .map((field) => field.trim())
  if (status !== 'C' && status !== 'F') continue
  folding[Number.parseInt(point!, 16)] = mapping!
    .split(' ')
    .map((part) => Number.parseInt(part, 16))
}

const output = new URL(
  '../../packages/morphir-workspace/src/artifact-unicode-data.ts',
  import.meta.url,
)
const packageLicense = new URL(
  '../../packages/morphir-workspace/UNICODE-LICENSE.txt',
  import.meta.url,
)
const licenseText = sources.get('LICENSE.txt')!
const generated = await format(
  `/*!\n${licenseText}\n*/
// Generated by tools/unicode/generate-artifact-unicode.ts. Do not edit.
// Unicode data copyright Unicode, Inc. See tools/unicode/LICENSE.txt and manifest.json.
// Normalization 17.0.0; full default case folding 9.0.0. No runtime Unicode tables.
export const decomposition: Readonly<Record<number, {readonly compatibility: boolean; readonly mapping: readonly number[]}>> = ${JSON.stringify(decomposition)}
export const combiningClass: Readonly<Record<number, number>> = ${JSON.stringify(combining)}
export const composition: Readonly<Record<number, Readonly<Record<number, number>>>> = ${JSON.stringify(composition)}
export const fullDefaultCaseFold: Readonly<Record<number, readonly number[]>> = ${JSON.stringify(folding)}
`,
  { ...(await resolveConfig(fileURLToPath(output))), parser: 'typescript' },
)
if (values.check) {
  if ((await readFile(output, 'utf8')) !== generated)
    throw new Error('Generated Unicode tables differ')
  if ((await readFile(packageLicense, 'utf8')) !== licenseText)
    throw new Error('Packaged Unicode license differs')
} else {
  await writeFile(output, generated)
  await writeFile(packageLicense, licenseText)
}
console.log(
  `Unicode sources and tables ${values.check ? 'verified' : 'generated'}: ${digest(new TextEncoder().encode(generated))}`,
)
